    """
    This function tests the interference simulation in the scene simulator
    """
    f_offset_int = np.arange(0, 8) * 70e6
    int_tx = Transmitter(
        f=[60.4e9, 60.6e9],
        t=[0, 8e-6],
        tx_power=15,
        prp=11e-6,
        pulses=8,
        f_offset=f_offset_int,
        channels=[
            {"location": (0, 0.1, 0), "pulse_phs": np.array([0, 180, 0, 0, 0, 0, 0, 0])}
        ],
    )

    int_rx = Receiver(
        fs=20e6,
        noise_figure=8,
        rf_gain=20,
        load_resistor=500,
        baseband_gain=30,
        channels=[{"location": (0, 0.1, 0)}],
    )

    int_radar = Radar(
        transmitter=int_tx, receiver=int_rx, location=(30, 0, 0), rotation=(180, 0, 0)
    )

    f_offset_vit = np.arange(0, 4) * 90e6
    tx = Transmitter(
        f=[60.6e9, 60.4e9],
        t=[0, 16e-6],
        tx_power=25,
        prp=20e-6,
        pulses=4,
        f_offset=f_offset_vit,
        channels=[{"location": (0, 0, 0), "pulse_phs": np.array([180, 0, 0, 0])}],
    )

    rx = Receiver(
        fs=40e6,
        noise_figure=2,
        rf_gain=20,
        load_resistor=500,
        baseband_gain=60,
        channels=[{"location": (0, 0, 0)}],
    )

